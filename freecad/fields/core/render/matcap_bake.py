"""The matcap image model: materials rendered against an analytic environment.

numpy only -- no FreeCAD or Qt -- so the preset generator
(`Resources/matcaps/generate_presets.py`), the in-app colour-variant bake and the
headless tests all share one implementation.

A `Material` is a base colour, metallic, roughness and a dielectric specular level,
seen in one of the `ENVIRONMENTS`. Metallic blends the diffuse colour toward black and
the specular colour from grey toward the base colour, so a dielectric's highlights stay
white and a metal's take its colour. Rendering sums, in linear light:

* **diffuse** = albedo x the cosine-weighted hemisphere integral of the environment.
  Irradiance is smooth, so it is evaluated on a 64x64 grid of sphere normals and
  bilinearly upsampled -- that integral is where the time goes (it was 5.2 s at
  full resolution) and nothing visible is lost.
* **gloss** = spec x the environment along the mirror direction, evaluated per texel
  at full resolution, so the lights stay crisp. `gloss` softens what is seen in it.

Never a single point light, and never a downloaded image: the lighting is an
environment integral, and every asset is generated by this code. Deterministic (no
randomness), so a variant re-baked on another machine matches.
"""
import functools
from dataclasses import dataclass, replace

import numpy as np

SIZE = 256
#: Side of the grid irradiance is evaluated on before upsampling to SIZE.
IRRADIANCE_GRID = 64


# ---- model -----------------------------------------------------------------

@dataclass(frozen=True)
class Environment:
    zenith: tuple
    horizon: tuple
    ground: tuple
    lights: tuple            # ((direction, colour, width), ...)


@dataclass(frozen=True)
class Material:
    env: str                 # key into ENVIRONMENTS
    color: tuple             # LINEAR rgb base colour: a dielectric's diffuse colour,
                             # a metal's reflection tint
    metallic: float          # 0 = dielectric (white highlights) .. 1 = metal (tinted, no diffuse)
    roughness: float         # 0 = sharp, mirror-like .. 1 = broad sheen
    specular: float = 0.0    # LINEAR dielectric highlight strength; fades out as metallic -> 1

    @property
    def albedo(self):
        """LINEAR diffuse colour: the base colour, fading to black as metallic -> 1."""
        k = self.metallic
        return tuple(c * (1.0 - k) for c in self.color)

    @property
    def spec(self):
        """LINEAR specular colour: grey `specular` for a dielectric, the base colour for a metal."""
        k = self.metallic
        return tuple(self.specular * (1.0 - k) + c * k for c in self.color)

    @property
    def gloss(self):
        return 1.0 - self.roughness


