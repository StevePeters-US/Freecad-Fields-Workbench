def variant_of(m, color_srgb, metallic, roughness):
    """`m` with its base colour (sRGB, 0-1), metallic and roughness replaced. The
    environment and the dielectric specular level stay `m`'s."""
    return replace(m, color=tuple(float(v) for v in _srgb_decode(color_srgb)),
                   metallic=float(metallic), roughness=float(roughness))


def base_color_srgb(m):
    """`m`'s base colour as colour-picker (sRGB, 0-1) values, for pre-filling an editor."""
    return tuple(float(v) for v in _srgb_encode(np.asarray(m.color)))


# ---- geometry and maths -----------------------------------------------------

def _smoothstep(e0, e1, x):
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def _sphere_normals(size=SIZE):
    """(n, mask): n is (size, size, 3) unit normals with +Y up; mask is the disc.

    Outside the disc the normal is projected onto the rim (nz = 0), so smooth
    functions of the normal stay smooth across the edge.
    """
    half = size / 2.0
    xs = (np.arange(size) - half + 0.5) / half
    ys = (half - np.arange(size) - 0.5) / half
    nx, ny = np.meshgrid(xs, ys)
    r2 = nx * nx + ny * ny
    mask = r2 <= 1.0
    scale = np.where(mask, 1.0, 1.0 / np.sqrt(np.maximum(r2, 1e-12)))
    nx, ny = nx * scale, ny * scale
    nz = np.sqrt(np.clip(1.0 - nx * nx - ny * ny, 0.0, 1.0))
    return np.stack([nx, ny, nz], axis=-1), mask


def _environment(d, env, scale=1.0, soft=0.0, light_gain=1.0):
    """Radiance of the analytic environment along directions d, shape (..., 3).

    Camera looks down -Z, so +Z points back at the viewer; +Y is up. `soft` (0..1)
    broadens the light lobes and the horizon edge, for a less glossy surface;
    `light_gain` brightens the lights only (a glossy surface mirrors a light at its
    full radiance, far above the sky's).
    """
    up = d[..., 1:2]
    zenith, horizon, ground = (np.asarray(c) * scale for c in (env.zenith, env.horizon, env.ground))
    sky_t = _smoothstep(0.0, 1.0, np.clip(up, 0.0, 1.0))
    sky = horizon * (1.0 - sky_t) + zenith * sky_t
    gnd_t = _smoothstep(0.0, 1.0, np.clip(-up, 0.0, 1.0))
    below = horizon * 0.25 * (1.0 - gnd_t) + ground * gnd_t
    edge = 0.08 + soft * 0.4          # a soft horizon line, not a hard cut
    out = below + (sky - below) * _smoothstep(-edge, edge, up)
    for direction, colour, width in env.lights:
        ld = np.asarray(direction, dtype=np.float64)
        ld = ld / np.linalg.norm(ld)
        c = np.sum(d * ld, axis=-1, keepdims=True)
        out = out + np.asarray(colour) * light_gain * _smoothstep(1.0 - (width + soft * 0.5), 1.0, c)
    return out


def _hemisphere_basis(n):
    helper = np.where(np.abs(n[..., 1:2]) < 0.99,
                      np.array([0.0, 1.0, 0.0]), np.array([1.0, 0.0, 0.0]))
    t = np.cross(helper, n)
    t /= np.linalg.norm(t, axis=-1, keepdims=True)
    return t, np.cross(n, t)


def _irradiance(n, env):
    """Cosine-weighted hemisphere mean of the environment around normals n."""
    t, b = _hemisphere_basis(n)
    n_theta, n_phi = 16, 32
    acc = np.zeros(n.shape)
    for i in range(n_theta):
        u1 = (i + 0.5) / n_theta
        sin_t, cos_t = np.sqrt(u1), np.sqrt(1.0 - u1)
        for j in range(n_phi):
            phi = 2.0 * np.pi * (j + 0.5) / n_phi
            d = t * (sin_t * np.cos(phi)) + b * (sin_t * np.sin(phi)) + n * cos_t
            acc += _environment(d, env)
    return acc / (n_theta * n_phi)


def _upsample(coarse, size=SIZE):
    """Bilinear (g, g, c) -> (size, size, c), keeping texel-centre alignment."""
    g = coarse.shape[0]
    pos = (np.arange(size) + 0.5) * (g / size) - 0.5
    pos = np.clip(pos, 0.0, g - 1.0)
    i0 = np.floor(pos).astype(int)
    i1 = np.minimum(i0 + 1, g - 1)
    f = (pos - i0)[:, None]
    rows = coarse[i0] * (1.0 - f)[:, :, None] + coarse[i1] * f[:, :, None]
    fx = (pos - i0)[None, :, None]
    return rows[:, i0] * (1.0 - fx) + rows[:, i1] * fx


@functools.lru_cache(maxsize=None)
def _coarse_irradiance(env_name):
    """Upsampled diffuse irradiance of one environment: (SIZE, SIZE, 3), read-only.

    Depends on the environment only, so every material and variant lit by it shares
    one evaluation -- 256 ms of a 270 ms bake (measured 2026-10-06). ENVIRONMENTS is a
    module constant; nothing may mutate it at run time, or this goes stale.
    """
    n, _ = _sphere_normals(IRRADIANCE_GRID)
    irr = _upsample(_irradiance(n, ENVIRONMENTS[env_name]))
    irr.setflags(write=False)
    return irr


def _diffuse(m, coarse=True):
    """Linear diffuse term over the whole SIZE x SIZE grid (outside-disc included)."""
    if coarse:
        irr = _coarse_irradiance(m.env)
    else:
        n, _ = _sphere_normals(SIZE)
        irr = _irradiance(n, ENVIRONMENTS[m.env])
    return np.asarray(m.albedo) * irr


def _gloss(m, n):
    """Linear specular term: the environment along the mirror direction."""
    env = ENVIRONMENTS[m.env]
    soft = 1.0 - m.gloss
    k = m.metallic
    view = np.array([0.0, 0.0, 1.0])
    r = 2.0 * np.sum(n * view, axis=-1, keepdims=True) * n - view
    # A mirror shows a light at full radiance, well above the sky's: without the
    # gain a plastic's highlight is too dim to read as white over its colour.
    e = _environment(r, env, scale=0.5 * (1.0 - k) + 1.0 * k, soft=soft,
                     light_gain=1.0 + 16.0 * m.gloss ** 2)
    fres = (1.0 - np.clip(n[..., 2:3], 0.0, 1.0)) ** 3
    floor = 0.25 * (1.0 - k) + 0.8 * k
    return np.asarray(m.spec) * e * (floor + (1.0 - floor) * fres)


# ---- renders -----------------------------------------------------------------

def render_material(m):
    """The (SIZE, SIZE, 4) uint8 RGBA image of a Material."""
    n, mask = _sphere_normals()
    lin = _diffuse(m) + _gloss(m, n)
    rgb = np.where(mask[..., None], _srgb_encode(lin), 0.0)     # black outside the disc
    return _to_u8(rgb, mask.astype(np.float64))


def _to_u8(rgb, alpha):
    img = np.concatenate([rgb, alpha[..., None]], axis=-1)
    return np.clip(np.round(img * 255.0), 0, 255).astype(np.uint8)


def _render_normals():
    n, mask = _sphere_normals()
    return _to_u8(np.where(mask[..., None], n * 0.5 + 0.5, 0.0), mask.astype(np.float64))


def _render_zebra():
    n, mask = _sphere_normals()
    val = np.sin((n[..., 0] * 0.707 + n[..., 1] * 0.707) * 20.0)
    s = _smoothstep(-0.05, 0.05, val)
    rgb = np.where(mask[..., None], np.stack([s, s, s], axis=-1), 0.0)
    return _to_u8(rgb, mask.astype(np.float64))


def _render_curvature():
    """Diverging blue -> grey -> red along X, identical on every row; fills the image."""
    u = (np.arange(SIZE) + 0.5) / SIZE
    blue, grey, red = (np.array(c) for c in ((0.13, 0.30, 0.78), (0.62, 0.62, 0.62),
                                             (0.80, 0.16, 0.12)))
    lo = u[:, None] < 0.5
    t = np.where(lo, u[:, None] / 0.5, (u[:, None] - 0.5) / 0.5)
    row = np.where(lo, blue + (grey - blue) * t, grey + (red - grey) * t)
    rgb = np.broadcast_to(row[None, :, :], (SIZE, SIZE, 3)).copy()
    return _to_u8(_srgb_encode(rgb), np.ones((SIZE, SIZE)))


def render(name):
    """The (SIZE, SIZE, 4) uint8 RGBA image for a built-in preset name."""
    if name in MATERIALS:
        return render_material(MATERIALS[name])
    return {"normals": _render_normals, "zebra": _render_zebra,
            "curvature": _render_curvature}[name]()
