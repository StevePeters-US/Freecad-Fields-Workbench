def _srgb_decode(c):
    c = np.asarray(c, dtype=np.float64)
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def _srgb_encode(lin):
    lin = np.clip(lin, 0.0, 1.0)
    return np.where(lin <= 0.0031308, lin * 12.92, 1.055 * np.power(lin, 1 / 2.4) - 0.055)


def _mat(env, color_srgb, metallic, roughness, specular_srgb=0.0):
    """Build a Material from colour-picker (sRGB) values."""
    return Material(env, tuple(float(v) for v in _srgb_decode(color_srgb)), float(metallic),
                    float(roughness), float(_srgb_decode(specular_srgb)))


